#!/usr/bin/env python3
"""Measure the served corpus, and publish the measurement as data.

    dataset_quality.py            rewrite data/serveable/api/meta/dataset_quality.json
    dataset_quality.py --check    assert the committed file matches a fresh measurement

WHY THIS EXISTS.

The funding page is about to describe the open dataset as a thing worth paying
to maintain, and the most persuasive passage in it is the self-criticism: how
much of the corpus is unparsed bulk import. That passage is only worth having if
the numbers are right, because a funder can check them in thirty seconds against
a public JSON file.

On 2026-08-17 a draft of that page carried "801 of 1,194 event descriptions
literally begin 'Introduction'". Measured: **35** begin with it. What is true is
that **970** -- 81 percent -- CONTAIN the word somewhere, which is a different
and slightly weaker claim. "801" appears to be "81 percent" with the decimal
lost. Wrong count, wrong predicate, and it would have been published.

So the counts stop being prose. They are computed here, served as a public
artefact, and `--check` fails the build if the committed file stops matching the
corpus. A number that regenerates cannot go stale; a number in a sentence can,
and this one did within two days of being written down.

WHAT IT DOES NOT DO.

It does not judge. Every field is a count or a proportion with a stated
predicate, and the interpretation -- whether 989 short descriptions is a scandal
or a known consequence of a bulk import nobody has parsed yet -- belongs to
whoever writes the copy. That split is the same one ADR-001 draws everywhere
else in this repo: facts here, shaping downstream.
"""

import argparse
import json
import os
import statistics
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
EVENTS = os.path.join(REPO, "data", "serveable", "api", "timeline_events",
                      "all_events.json")
OUT_DIR = os.path.join(REPO, "data", "serveable", "api", "meta")
OUT = os.path.join(OUT_DIR, "dataset_quality.json")

SHORT_CHARS = 60


def family(slug):
    """Which import a record came from. Prefix-based, and deliberately coarse."""
    for prefix in ("arxiv", "distill", "alignmentforum"):
        if slug.startswith(prefix):
            return prefix
    return "hand_authored"


def measure():
    with open(EVENTS, encoding="utf-8") as fh:
        events = json.load(fh)

    rows = [(slug, (rec.get("description") or "")) for slug, rec in events.items()]
    lengths = sorted(len(text) for _, text in rows)

    fam = {}
    for slug, _ in rows:
        fam[family(slug)] = fam.get(family(slug), 0) + 1

    starts_intro = sum(1 for _, t in rows
                       if t.strip().lower().startswith("introduction"))
    contains_intro = sum(1 for _, t in rows if "introduction" in t.lower())
    short = sum(1 for _, t in rows if len(t) < SHORT_CHARS)
    empty = sum(1 for _, t in rows if not t.strip())

    total = len(rows)

    def pct(n):
        return round(100.0 * n / total, 1) if total else None

    return {
        "_README": ("Measured facts about the served timeline_events corpus. "
                    "Regenerated by scripts/analysis/dataset_quality.py and "
                    "checked in CI. Counts only -- no judgement. If you are "
                    "quoting one of these in public copy, quote it from here "
                    "rather than retyping it."),
        "_measured_from": "data/serveable/api/timeline_events/all_events.json",
        "total_events": total,
        "by_import": fam,
        "description": {
            "_predicates_matter": ("These three are different claims and have "
                                   "been confused before. Read the key."),
            "under_60_chars": short,
            "under_60_chars_pct": pct(short),
            "starts_with_introduction": starts_intro,
            "starts_with_introduction_pct": pct(starts_intro),
            "contains_introduction_anywhere": contains_intro,
            "contains_introduction_anywhere_pct": pct(contains_intro),
            "empty": empty,
            "length_chars": {
                "min": lengths[0] if lengths else None,
                "median": int(statistics.median(lengths)) if lengths else None,
                "mean": int(statistics.mean(lengths)) if lengths else None,
                "max": lengths[-1] if lengths else None,
            },
        },
        "_correction_2026_08_17": (
            "A draft funding page carried '801 of 1,194 descriptions literally "
            "begin Introduction'. Measured: 35 begin with it; 970 (81 percent) "
            "contain it somewhere. 801 looks like 81 percent with the decimal "
            "lost. Wrong count AND wrong predicate, in a passage a reader could "
            "check against this very file. That is why these are computed now."),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    if not os.path.isfile(EVENTS):
        sys.stderr.write("no served events at %s\n" % EVENTS)
        return 2

    fresh = json.dumps(measure(), indent=2, sort_keys=True, ensure_ascii=True) + "\n"

    if args.check:
        if not os.path.isfile(OUT):
            print("CHECK FAILED: %s does not exist" % os.path.relpath(OUT, REPO))
            return 1
        with open(OUT, encoding="utf-8") as fh:
            committed = fh.read()
        if committed != fresh:
            print("CHECK FAILED: dataset_quality.json disagrees with the corpus. "
                  "Re-run scripts/analysis/dataset_quality.py.")
            return 1
        data = json.loads(committed)
        print("CHECK OK: %d events; %d descriptions under %d chars (%.1f%%); "
              "%d start with 'Introduction', %d contain it."
              % (data["total_events"],
                 data["description"]["under_60_chars"], SHORT_CHARS,
                 data["description"]["under_60_chars_pct"],
                 data["description"]["starts_with_introduction"],
                 data["description"]["contains_introduction_anywhere"]))
        return 0

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(OUT, "w", encoding="ascii", newline="\n") as fh:
        fh.write(fresh)
    data = json.loads(fresh)
    print("wrote %s" % os.path.relpath(OUT, REPO))
    print("  %d events: %s" % (data["total_events"],
                               ", ".join("%s %d" % kv
                                         for kv in sorted(data["by_import"].items()))))
    d = data["description"]
    print("  under %d chars: %d (%.1f%%)"
          % (SHORT_CHARS, d["under_60_chars"], d["under_60_chars_pct"]))
    print("  starts 'Introduction': %d (%.1f%%)   contains it: %d (%.1f%%)"
          % (d["starts_with_introduction"], d["starts_with_introduction_pct"],
             d["contains_introduction_anywhere"],
             d["contains_introduction_anywhere_pct"]))
    print("  length chars: min %(min)d median %(median)d mean %(mean)d max %(max)d"
          % d["length_chars"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
